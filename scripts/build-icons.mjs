// Turns the Figma icon exports in assets/icons into src/design-system/icons.generated.ts.
// The SVGs are kept as exported; only the colour and stroke width become placeholders
// so <Icon> can tint them and keep the 1.75 stroke at every size.
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';

const dir = new URL('../assets/icons/', import.meta.url);
const out = new URL('../src/design-system/icons.generated.ts', import.meta.url);

const entries = readdirSync(dir)
  .filter((f) => f.endsWith('.svg'))
  .sort()
  .map((f) => {
    const xml = readFileSync(new URL(f, dir), 'utf8')
      .replace(/\s*style="[^"]*"/g, '')
      .replace(/#6B645A/gi, '{{color}}')
      .replace(/stroke-width="1\.75"/g, 'stroke-width="{{stroke}}"')
      .replace(/\n/g, '');
    return `  '${f.replace('.svg', '')}': ${JSON.stringify(xml)},`;
  });

writeFileSync(
  out,
  `// Generated by scripts/build-icons.mjs from assets/icons. Do not edit by hand.\n` +
    `export const iconXml = {\n${entries.join('\n')}\n} as const;\n\nexport type IconName = keyof typeof iconXml;\n`,
);
console.log(`Wrote ${entries.length} icons`);
