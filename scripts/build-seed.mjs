// Writes supabase/seed.sql from the hymns bundled in the app, plus the About page.
// Run: node scripts/build-seed.mjs   (then paste supabase/seed.sql into the Supabase SQL editor)
import { readFileSync, writeFileSync } from 'node:fs';

const root = new URL('..', import.meta.url);
const { hymns } = JSON.parse(readFileSync(new URL('src/data/hymns.json', root), 'utf8'));
const en = readFileSync(new URL('src/i18n/en.ts', root), 'utf8');
const aboutBody = /aboutBody:\s*\n?\s*'([^']*)'/.exec(en)?.[1] ?? '';

const q = (v) => (v === null || v === undefined ? 'null' : typeof v === 'number' ? String(v) : `'${String(v).replaceAll("'", "''")}'`);
const strip = (stanzas) => stanzas.map(({ inferred, ...s }) => s);

const rows = hymns.map((h) =>
  `(${[h.number, h.title, h.key, h.scripture, h.volume, h.volumeYear, h.author, h.year, h.credit].map(q).join(', ')}, ${q(JSON.stringify(strip(h.stanzas)))}::jsonb)`,
);

writeFileSync(
  new URL('supabase/seed.sql', root),
  `-- Generated by scripts/build-seed.mjs from src/data/hymns.json. Safe to run again: existing rows are left alone.
insert into public.hymns (number, title, key, scripture, volume, volume_year, author, year, credit, stanzas) values
${rows.join(',\n')}
on conflict (number) do nothing;

insert into public.pages (slug, title, body) values
('about', 'About Hoziana choir', ${q(aboutBody)})
on conflict (slug) do nothing;
`,
);
console.log(`supabase/seed.sql: ${rows.length} hymns`);
