// Adds an Android network security config so the app only talks over HTTPS, on every Android
// version. Apps targeting Android 9+ already block plain http:// by default, but only on phones
// running Android 9 or newer; this app supports Android 7 and 8 too, where http:// would otherwise
// be allowed. It also only trusts the phone's built-in certificate authorities, not ones a user or
// an MDM profile installed.
//
// Debug builds (debug and debugOptimized) get a separate, relaxed config, because their source
// sets override src/main, so the development server, which runs over http://, keeps working.
const fs = require('fs');
const path = require('path');
const { withAndroidManifest, withDangerousMod } = require('expo/config-plugins');

const RELEASE_CONFIG = `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by plugins/with-network-security.js -->
<network-security-config>
    <base-config cleartextTrafficPermitted="false">
        <trust-anchors>
            <certificates src="system" />
        </trust-anchors>
    </base-config>
</network-security-config>
`;

const DEBUG_CONFIG = `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by plugins/with-network-security.js. Debug builds only: lets the app reach the
     development server over http://. -->
<network-security-config>
    <base-config cleartextTrafficPermitted="true">
        <trust-anchors>
            <certificates src="system" />
            <certificates src="user" />
        </trust-anchors>
    </base-config>
</network-security-config>
`;

function writeConfig(projectRoot, sourceSet, contents) {
  const dir = path.join(projectRoot, 'android', 'app', 'src', sourceSet, 'res', 'xml');
  fs.mkdirSync(dir, { recursive: true });
  fs.writeFileSync(path.join(dir, 'network_security_config.xml'), contents);
}

module.exports = function withNetworkSecurity(config) {
  config = withDangerousMod(config, [
    'android',
    (config) => {
      writeConfig(config.modRequest.projectRoot, 'main', RELEASE_CONFIG);
      for (const sourceSet of ['debug', 'debugOptimized']) {
        writeConfig(config.modRequest.projectRoot, sourceSet, DEBUG_CONFIG);
      }
      return config;
    },
  ]);

  return withAndroidManifest(config, (config) => {
    const app = config.modResults.manifest.application?.[0];
    if (!app) throw new Error('with-network-security: AndroidManifest.xml has no <application>.');
    app.$['android:networkSecurityConfig'] = '@xml/network_security_config';
    // The config above is the single source of truth for cleartext; drop any older flag.
    delete app.$['android:usesCleartextTraffic'];
    return config;
  });
};
